#!/usr/bin/env node
/**
 * Tile swap guard for client/public/assets/tiles.
 *
 * For every `*.tsj` + png it verifies:
 *   1. the png size equals the margin/spacing/columns/rows math (and the tsj's own imagewidth/imageheight),
 *   2. tilecount and per-tile properties (id, collides, animationOnly) match docs/tiles-baseline.json,
 *   3. every tileset used by client/public/maps/*.tmj, terrain/biomes.js and terrain/generate.js
 *      (TILESET_CATALOG) has a tsj and a manifest entry that agree with each other.
 *
 * Usage:
 *   node tools/assets/check_tiles.mjs                   check, exit 1 with a diff on mismatch
 *   node tools/assets/check_tiles.mjs --write-baseline  regenerate docs/tiles-baseline.json from the
 *                                                       current tiles (only after an approved layout change)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(__filename), '../..');

export const BASELINE_REL = 'docs/tiles-baseline.json';
const BASELINE_VERSION = 1;

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));

/** Reads width/height from a PNG IHDR chunk. */
export function pngSize(file) {
  const buf = fs.readFileSync(file);
  const sig = buf.subarray(0, 8).toString('hex');
  if (sig !== '89504e470d0a1a0a' || buf.subarray(12, 16).toString('ascii') !== 'IHDR') {
    throw new Error(`not a PNG: ${file}`);
  }
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

/** Expected image size from the tileset layout. */
export function expectedImageSize({ tilewidth, tileheight, columns, tilecount, margin = 0, spacing = 0 }) {
  const rows = Math.ceil(tilecount / columns);
  return {
    rows,
    width: margin * 2 + columns * tilewidth + (columns - 1) * spacing,
    height: margin * 2 + rows * tileheight + (rows - 1) * spacing,
  };
}

function propValue(tile, name, fallback = false) {
  const p = (tile?.properties ?? []).find((x) => x.name === name);
  return p ? p.value : fallback;
}

/** Layout + per-tile facts for one tsj, in the shape stored in the baseline. */
export function summarizeTileset(tsj) {
  const byId = new Map((tsj.tiles ?? []).map((t) => [t.id, t]));
  const collides = [];
  const animationOnly = [];
  for (let id = 0; id < tsj.tilecount; id++) {
    const t = byId.get(id);
    if (propValue(t, 'collides')) collides.push(id);
    if (propValue(t, 'animationOnly')) animationOnly.push(id);
  }
  return {
    tilewidth: tsj.tilewidth,
    tileheight: tsj.tileheight,
    margin: tsj.margin ?? 0,
    spacing: tsj.spacing ?? 0,
    columns: tsj.columns,
    tilecount: tsj.tilecount,
    collides,
    animationOnly,
  };
}

function listTilesets(tilesDir) {
  return fs
    .readdirSync(tilesDir)
    .filter((f) => f.endsWith('.tsj'))
    .map((f) => f.slice(0, -4))
    .sort();
}

/** Builds the baseline object from the tiles currently on disk. */
export function buildBaseline({ root = REPO_ROOT, tilesDir = path.join(root, 'client/public/assets/tiles') } = {}) {
  const tilesets = {};
  for (const name of listTilesets(tilesDir)) {
    tilesets[name] = summarizeTileset(readJson(path.join(tilesDir, `${name}.tsj`)));
  }
  return {
    version: BASELINE_VERSION,
    note: 'Generated by tools/assets/check_tiles.mjs --write-baseline. Only regenerate for an approved tile layout change.',
    tilesets,
  };
}

const fmtIds = (ids) => (ids.length ? `[${ids.join(',')}]` : '[]');

function diffIdLists(label, want, got, out) {
  const w = new Set(want);
  const g = new Set(got);
  const added = got.filter((i) => !w.has(i));
  const removed = want.filter((i) => !g.has(i));
  if (added.length || removed.length) {
    out.push(`${label}: baseline ${fmtIds(want)} -> now ${fmtIds(got)} (added ${fmtIds(added)}, removed ${fmtIds(removed)})`);
  }
}

/**
 * Runs every check. Returns { ok, errors } where errors is a list of readable lines.
 * `tilesDir` and `baselinePath` can be overridden (the unit test points them at a temp copy).
 */
export async function checkTiles({
  root = REPO_ROOT,
  tilesDir = path.join(root, 'client/public/assets/tiles'),
  baselinePath = path.join(root, BASELINE_REL),
  mapsDir = path.join(root, 'client/public/maps'),
  manifestPath = path.join(root, 'client/public/assets/manifest.json'),
  biomesPath = path.join(root, 'client/src/game/terrain/biomes.js'),
  generatePath = path.join(root, 'client/src/game/terrain/generate.js'),
} = {}) {
  const errors = [];
  const err = (scope, msg) => errors.push(`${scope}: ${msg}`);

  const names = listTilesets(tilesDir);
  const tsjByName = {};

  // 1. image size math, per-tile id property sanity
  for (const name of names) {
    const tsj = readJson(path.join(tilesDir, `${name}.tsj`));
    tsjByName[name] = tsj;
    if (tsj.name !== name) err(name, `tsj "name" is "${tsj.name}", expected "${name}"`);
    const pngFile = path.join(tilesDir, `${name}.png`);
    if (tsj.image !== `${name}.png`) err(name, `tsj "image" is "${tsj.image}", expected "${name}.png"`);
    if (!fs.existsSync(pngFile)) {
      err(name, `missing ${name}.png`);
      continue;
    }
    const exp = expectedImageSize(tsj);
    const actual = pngSize(pngFile);
    if (actual.width !== exp.width || actual.height !== exp.height) {
      err(
        name,
        `png is ${actual.width}x${actual.height}, layout math says ${exp.width}x${exp.height} ` +
          `(${tsj.columns} cols x ${exp.rows} rows, ${tsj.tilewidth}x${tsj.tileheight} tiles, margin ${tsj.margin ?? 0}, spacing ${tsj.spacing ?? 0})`,
      );
    }
    if (tsj.imagewidth !== actual.width || tsj.imageheight !== actual.height) {
      err(name, `tsj says imagewidth/imageheight ${tsj.imagewidth}x${tsj.imageheight} but png is ${actual.width}x${actual.height}`);
    }
    for (const t of tsj.tiles ?? []) {
      const idProp = propValue(t, 'id', undefined);
      if (idProp !== undefined && idProp !== t.id) err(name, `tile ${t.id} has property id=${idProp}`);
      if (t.id >= tsj.tilecount) err(name, `tile id ${t.id} is outside tilecount ${tsj.tilecount}`);
    }
  }

  // 2. baseline
  if (!fs.existsSync(baselinePath)) {
    err('baseline', `missing ${path.relative(root, baselinePath)} (run with --write-baseline)`);
  } else {
    const baseline = readJson(baselinePath).tilesets ?? {};
    for (const name of Object.keys(baseline)) {
      if (!tsjByName[name]) err(name, 'in baseline but tsj is missing (tileset removed or renamed)');
    }
    for (const name of names) {
      const want = baseline[name];
      if (!want) {
        err(name, 'tsj is not in the baseline (new tileset; regenerate the baseline if approved)');
        continue;
      }
      const got = summarizeTileset(tsjByName[name]);
      const lines = [];
      for (const key of ['tilewidth', 'tileheight', 'margin', 'spacing', 'columns', 'tilecount']) {
        if (want[key] !== got[key]) lines.push(`${key}: baseline ${want[key]} -> now ${got[key]}`);
      }
      diffIdLists('collides', want.collides ?? [], got.collides, lines);
      diffIdLists('animationOnly', want.animationOnly ?? [], got.animationOnly, lines);
      for (const l of lines) err(name, l);
    }
  }

  // 3. usage: manifest, maps, biomes, wilderness catalog
  const manifest = fs.existsSync(manifestPath) ? readJson(manifestPath) : {};
  const manifestTiles = manifest.tiles ?? {};
  if (!fs.existsSync(manifestPath)) err('manifest', `missing ${path.relative(root, manifestPath)}`);

  for (const name of names) {
    const entry = manifestTiles[name];
    if (!entry) {
      err(name, 'no entry in manifest.json "tiles"');
      continue;
    }
    const tsj = tsjByName[name];
    for (const [mk, tk] of [
      ['tileWidth', 'tilewidth'],
      ['tileHeight', 'tileheight'],
      ['tileCount', 'tilecount'],
      ['margin', 'margin'],
      ['spacing', 'spacing'],
    ]) {
      if (entry[mk] !== (tsj[tk] ?? 0)) err(name, `manifest ${mk}=${entry[mk]} but tsj ${tk}=${tsj[tk]}`);
    }
    if (entry.tsj !== `assets/tiles/${name}.tsj`) err(name, `manifest tsj path is "${entry.tsj}"`);
    if (entry.image !== `assets/tiles/${name}.png`) err(name, `manifest image path is "${entry.image}"`);
  }
  for (const name of Object.keys(manifestTiles)) {
    if (!tsjByName[name]) err(name, 'in manifest.json "tiles" but has no tsj');
  }

  const used = new Map(); // tileset name -> Set of places that use it
  const use = (name, where) => {
    if (!used.has(name)) used.set(name, new Set());
    used.get(name).add(where);
  };

  if (fs.existsSync(mapsDir)) {
    for (const f of fs.readdirSync(mapsDir).filter((x) => x.endsWith('.tmj')).sort()) {
      const map = readJson(path.join(mapsDir, f));
      for (const ts of map.tilesets ?? []) {
        use(ts.name, `maps/${f}`);
        const tsj = tsjByName[ts.name];
        if (!tsj) continue;
        const diffs = [];
        for (const [mk, tk] of [
          ['tilewidth', 'tilewidth'],
          ['tileheight', 'tileheight'],
          ['columns', 'columns'],
          ['tilecount', 'tilecount'],
          ['margin', 'margin'],
          ['spacing', 'spacing'],
          ['imagewidth', 'imagewidth'],
          ['imageheight', 'imageheight'],
        ]) {
          if (ts[mk] !== undefined && ts[mk] !== tsj[tk]) diffs.push(`${mk} map=${ts[mk]} tsj=${tsj[tk]}`);
        }
        if (diffs.length) err(ts.name, `maps/${f} embeds a stale copy of the tileset: ${diffs.join(', ')}`);
      }
    }
  }

  if (fs.existsSync(biomesPath)) {
    const { BIOMES } = await import(pathToFileURL(biomesPath).href);
    for (const b of Object.values(BIOMES)) {
      if (b.groundTileId) use(b.groundTileId, `biomes.js (${b.id}.groundTileId)`);
      if (b.pathTileId) use(b.pathTileId, `biomes.js (${b.id}.pathTileId)`);
    }
  }

  if (fs.existsSync(generatePath)) {
    const { TILESET_CATALOG } = await import(pathToFileURL(generatePath).href);
    for (const c of TILESET_CATALOG ?? []) {
      use(c.name, 'generate.js TILESET_CATALOG');
      const tsj = tsjByName[c.name];
      if (!tsj) continue;
      if (c.count !== tsj.tilecount) err(c.name, `generate.js TILESET_CATALOG count=${c.count} but tsj tilecount=${tsj.tilecount}`);
      if (c.margin !== (tsj.margin ?? 0) || c.spacing !== (tsj.spacing ?? 0)) {
        err(c.name, `generate.js TILESET_CATALOG margin/spacing ${c.margin}/${c.spacing} but tsj ${tsj.margin}/${tsj.spacing}`);
      }
    }
  }

  for (const [name, where] of [...used.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const places = [...where].slice(0, 3).join(', ') + (where.size > 3 ? `, +${where.size - 3} more` : '');
    if (!tsjByName[name]) err(name, `used by ${places} but there is no ${name}.tsj`);
    if (!manifestTiles[name]) err(name, `used by ${places} but there is no manifest.json "tiles" entry`);
  }

  return { ok: errors.length === 0, errors, tilesetCount: names.length };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes('--write-baseline')) {
    const file = path.join(REPO_ROOT, BASELINE_REL);
    const baseline = buildBaseline();
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, `${JSON.stringify(baseline, null, 2)}\n`);
    console.log(`Wrote ${BASELINE_REL} (${Object.keys(baseline.tilesets).length} tilesets)`);
    return;
  }
  const { ok, errors, tilesetCount } = await checkTiles();
  if (ok) {
    console.log(`check_tiles: OK (${tilesetCount} tilesets match ${BASELINE_REL}, maps, biomes and manifest)`);
    return;
  }
  console.error(`check_tiles: ${errors.length} problem(s)\n`);
  for (const e of errors) console.error(`  - ${e}`);
  console.error(
    '\nIf this is an approved layout change, fix the maps/manifest/code first, then run:\n  node tools/assets/check_tiles.mjs --write-baseline',
  );
  process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main().catch((e) => {
    console.error(e);
    process.exitCode = 2;
  });
}
